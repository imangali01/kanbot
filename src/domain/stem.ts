export const normalizeText = (s: string): string => s.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();

export const words = (s: string): string[] => s.split(/[^\p{L}\p{N}]+/u).filter(Boolean);

// Окончания русских существительных, прилагательных и глаголов, длинные раньше коротких.
const ENDINGS = [
  'иями', 'ившись', 'ывшись', 'ейте', 'уйте',
  'ями', 'ами', 'иях', 'ием', 'ией', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ешь', 'ишь', 'ует', 'уют', 'ете', 'ите', 'ать', 'ять', 'еть', 'уть', 'ить', 'ыть', 'ила', 'ыла', 'ило', 'ыло', 'или', 'ыли', 'ены', 'ено', 'нно',
  'ях', 'ям', 'ах', 'ам', 'ом', 'ем', 'ой', 'ей', 'ий', 'ый', 'ые', 'ие', 'ое', 'ее', 'ую', 'юю', 'ая', 'яя', 'ою', 'ею', 'ия', 'ья', 'ью', 'ию', 'ых', 'их', 'ым', 'им', 'ут', 'ют', 'ат', 'ят', 'ет', 'ит', 'ыт', 'ла', 'ло', 'ли', 'на', 'но', 'ны', 'ов', 'ев', 'ье', 'ен', 'ил', 'ыл',
  'а', 'я', 'о', 'е', 'у', 'ю', 'ы', 'и', 'ь', 'й',
];
const MIN_STEM = 3;

/** Лёгкий стеммер русских слов: отбрасывает одно окончание. Остальные слова (латиница, цифры) не трогает. */
export function stemRu(word: string): string {
  if (!/^[а-я]+$/.test(word)) return word;
  for (const end of ENDINGS) {
    if (word.length - end.length >= MIN_STEM && word.endsWith(end)) return word.slice(0, -end.length);
  }
  return word;
}
